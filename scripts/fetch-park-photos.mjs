#!/usr/bin/env node
/**
 * Downloads the reviewed Commons picks into public/img/parks as webp, and
 * writes lib/data/park-reference-photos.ts with the attribution each licence
 * requires.
 *
 *   npm run fetch:photos
 *
 * Copies are held locally rather than hot-linked. Two reasons: the map should
 * not depend on someone else's server being up to render, and repeatedly
 * pulling full-size originals from Commons for every page view is rude.
 *
 * Every licence here (CC BY, CC BY-SA, CC0, public domain) permits
 * redistribution. CC BY and CC BY-SA require the author and licence to travel
 * with the image, which is why the generated file carries both and the UI shows
 * them. Dropping the credit is not a style choice, it is a licence breach.
 */
import { mkdirSync, writeFileSync, readFileSync, existsSync, statSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const UA = "BallparkTracker/0.1 (personal project; contact via GitHub Jabberwocky7777)";
const OUT_DIR = join("public", "img", "parks");
const WIDTH = 480; // the hover card is 170px; 480 covers retina and the park page

const picks = JSON.parse(readFileSync("park-photo-picks.json", "utf8"));
mkdirSync(OUT_DIR, { recursive: true });

const entries = [];
for (const [venueId, p] of Object.entries(picks)) {
  process.stderr.write(`${venueId.padEnd(16)} `);
  const target = join(OUT_DIR, `${venueId}.webp`);
  // Resumable: Commons throttles hard, and a rerun should cost only what is
  // actually missing.
  if (existsSync(target) && statSync(target).size > 2000) {
    entries.push({ venueId, ...p, bytes: statSync(target).size });
    process.stderr.write("cached\n");
    continue;
  }

  try {
    // Ask Commons for a sensible width rather than pulling a 20MP original.
    const url = p.remoteUrl.replace(/\/\d+px-/, `/${WIDTH * 2}px-`);
    let buf = null;
    for (let attempt = 0; attempt < 5 && !buf; attempt++) {
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (res.ok) {
        buf = Buffer.from(await res.arrayBuffer());
        break;
      }
      if (res.status !== 429) throw new Error(`HTTP ${res.status}`);
      const wait = 5000 * (attempt + 1);
      process.stderr.write(`[429, waiting ${wait / 1000}s] `);
      await new Promise((r) => setTimeout(r, wait));
    }
    if (!buf) throw new Error("throttled after 5 attempts");

    const out = await sharp(buf)
      .resize(WIDTH, Math.round((WIDTH * 10) / 16), { fit: "cover", position: "centre" })
      .webp({ quality: 78 })
      .toBuffer();

    writeFileSync(target, out);
    entries.push({ venueId, ...p, bytes: out.length });
    process.stderr.write(`${(out.length / 1024).toFixed(0)}kB\n`);
  } catch (err) {
    process.stderr.write(`FAILED ${err.message}\n`);
  }
  await new Promise((r) => setTimeout(r, 1200));
}

const lines = entries
  .map(
    (e) => `  ${JSON.stringify(e.venueId)}: {
    file: "/img/parks/${e.venueId}.webp",
    author: ${JSON.stringify(e.author)},
    licence: ${JSON.stringify(e.licence)},
    licenceUrl: ${JSON.stringify(e.licenceUrl ?? null)},
    sourceUrl: ${JSON.stringify(e.sourceUrl)},
  },`,
  )
  .join("\n");

writeFileSync(
  join("lib", "data", "park-reference-photos.ts"),
  `/**
 * Freely-licensed reference photos, one per park, from Wikimedia Commons.
 *
 * GENERATED by scripts/fetch-park-photos.mjs from a hand-reviewed pick list --
 * edit park-photo-picks.json and re-run rather than editing this file.
 *
 * These are stand-ins shown until the couple publish a photo of their own for
 * that park, at which point theirs wins. Every entry is CC BY, CC BY-SA, CC0 or
 * public domain, and the first two of those require the author and licence to
 * be shown wherever the image is. The credit is a condition of use, not
 * decoration: do not remove it, and do not add an image here without one.
 *
 * Parks with no entry had no usable free photo taken from behind home plate.
 * That is deliberate -- the slot stays empty rather than showing the wrong shot.
 */
export interface ReferencePhoto {
  file: string;
  author: string;
  licence: string;
  licenceUrl: string | null;
  sourceUrl: string;
}

export const referencePhotos: Record<string, ReferencePhoto> = {
${lines}
};
`,
);

console.error(`\n${entries.length} photos in ${OUT_DIR}`);
console.error(`Total ${(entries.reduce((s, e) => s + e.bytes, 0) / 1024 / 1024).toFixed(2)} MB`);
